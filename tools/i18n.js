#!/usr/bin/env node
/* Bilingual content checker for the academy.

   node tools/i18n.js check            exit 1 if any English content string has no Persian translation
   node tools/i18n.js missing [group]  print missing strings as JSON: { group: { key: "English" } }
   node tools/i18n.js review           write docs/i18n-review.md (English and Persian side by side)

   Content strings (slides, notes, quizzes, pages) are translated through dictionaries in
   assets/i18n/fa/<group>.js, keyed by ACADEMY.key(english). UI and widget strings use
   L('English', 'فارسی') inline and are checked by the "inline" rule below. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const scripts = [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);

const ctx = { console };
ctx.window = ctx;
vm.createContext(ctx);
const run = (rel) => vm.runInContext(fs.readFileSync(path.join(ROOT, rel), 'utf8'), ctx, { filename: rel });

const found = new Map(); // key -> { en, group }
let group = 'core';
const isLeaf = (A, s) => {
  if (A.produced.has(s)) return false;
  if (/<(div|svg|figure|table|ol) |<ul class=|<p class="lead"/.test(s)) return false;
  const text = s.replace(/<code>[\s\S]*?<\/code>/g, ' ').replace(/<[^>]+>/g, ' ').replace(/&[a-z#0-9]+;/gi, ' ');
  return /[A-Za-z]{2,}/.test(text);
};

run('assets/js/core.js');
const A = ctx.ACADEMY;
A.collect = (s) => {
  if (!isLeaf(A, s)) return;
  const k = A.key(s);
  if (!found.has(k)) found.set(k, { en: s, group });
};
for (const src of scripts) {
  if (src.endsWith('core.js') || src.endsWith('app.js') || /widgets/.test(src)) continue;
  const m = src.match(/content\/(m\d+)/);
  group = src.includes('/i18n/') ? 'dict' : m ? m[1] : path.basename(src, '.js');
  if (group === 'dict') { run(src); continue; }
  if (group === 'notes') continue; // notes are collected with their module below
  run(src);
}
run('assets/js/notes.js');
// Module meta, slide titles, notes and quizzes
A.modules.forEach((m) => {
  group = 'm' + String(m.num).padStart(2, '0');
  const t = A.tr;
  t(m.title); t(m.summary); (m.outcomes || []).forEach(t);
  m.lessons.forEach((l) => { t(l.title); l.slides.forEach((s) => { t(s.t); if (s.n) t(s.n); }); });
  (m.quiz || []).forEach((q) => { t(q.q); q.a.forEach(t); t(q.why); });
});
// Reference pages
group = 'pages';
Object.values(A.pages).forEach((p) => {
  A.tr(p.title); if (p.eyebrow) A.tr(p.eyebrow);
  const d = Object.getOwnPropertyDescriptor(p, 'lead');
  if (d && !d.get && p.lead) A.tr(p.lead);
  p.render();
});

const fa = A.dicts.fa;
const missing = {};
for (const [k, v] of found) if (fa[k] == null) (missing[v.group] = missing[v.group] || {})[k] = v.en;
const nMissing = Object.values(missing).reduce((a, g) => a + Object.keys(g).length, 0);

// Inline rule: every L( call in UI/widget code must pass two string arguments.
const inlineProblems = [];
for (const f of ['assets/js/app.js', 'assets/js/widgets.js', 'assets/js/widgets-labs.js', 'assets/js/widgets-eco.js', 'assets/js/core.js', 'assets/js/pages.js']) {
  const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  for (const m of src.matchAll(/\bL\((['"`])((?:\\.|(?!\1).)*)\1\s*\)/g)) inlineProblems.push(`${f}: L(${m[1]}${m[2].slice(0, 50)}…) has no Persian`);
}

const mode = process.argv[2] || 'check';
if (mode === 'missing') {
  const g = process.argv[3];
  console.log(JSON.stringify(g ? { [g]: missing[g] || {} } : missing, null, 1));
} else if (mode === 'review') {
  const rows = [...found].map(([k, v]) => `| ${v.group} | ${v.en.replace(/\|/g, '\\|').replace(/\n/g, ' ')} | ${(fa[k] === '=' ? '(same)' : fa[k] || '**MISSING**').replace(/\|/g, '\\|').replace(/\n/g, ' ')} |`);
  fs.writeFileSync(path.join(ROOT, 'docs/i18n-review.md'), `# English ↔ Persian review\n\nGenerated by \`node tools/i18n.js review\`.\n\n| Group | English | فارسی |\n|---|---|---|\n${rows.join('\n')}\n`);
  console.log(`wrote docs/i18n-review.md (${rows.length} strings)`);
} else {
  const total = found.size;
  console.log(`content strings: ${total} · translated: ${total - nMissing} · missing: ${nMissing}`);
  Object.entries(missing).forEach(([g, o]) => console.log(`  ${g}: ${Object.keys(o).length} missing`));
  inlineProblems.forEach((p) => console.log('  ' + p));
  const unused = Object.keys(fa).filter((k) => !found.has(k));
  if (unused.length) console.log(`  note: ${unused.length} dictionary entries are no longer used`);
  process.exit(nMissing || inlineProblems.length ? 1 : 0);
}
